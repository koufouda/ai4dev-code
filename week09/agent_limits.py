"""Διάλεξη 18: όταν ο agent δεν σταματά. Όριο βημάτων, όριο κόστους, επαναλήψεις.

Χρήση:  python agent_limits.py
"""
from pythia_agent import agent

print("=== 1. Αδύνατη εργασία, όριο 5 βημάτων ===")
r = agent("Βρες όλες τις παραγγελίες της Μαρίας Παπαδοπούλου και πες μου το σύνολο.", max_steps=5)
print(f"→ σταμάτησε: {r['stopped']} | {len(r['steps'])} ενέργειες | ${r['cost']:.5f}\n")

print("=== 2. Εργασία πολλών βημάτων, όριο κόστους $0.001 ===")
r = agent("Η παραγγελία 41188 έχει μια ΜΠ-001 που γράφει E05. Καλύπτεται ακόμα από την εγγύηση; Τι να κάνω;", max_cost=0.001)
print(f"→ σταμάτησε: {r['stopped']} | {len(r['steps'])} ενέργειες | ${r['cost']:.5f}")
